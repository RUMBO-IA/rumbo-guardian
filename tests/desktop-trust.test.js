'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const workflow=fs.readFileSync(path.join(root,'.github','workflows','desktop-build.yml'),'utf8').replace(/\r\n/g,'\n');
const start=workflow.indexOf('  windows-nsis:\n');
const second=workflow.indexOf('  attest-windows:\n');
assert.ok(start>=0 && second>start,'both build and attest jobs must exist');
const build=workflow.slice(start,second);
const attest=workflow.slice(second);
assert.match(workflow,/pull_request:\s*\n\s+branches:\s*\n\s+- main/);
assert.match(workflow,/workflow_dispatch:/);
assert.doesNotMatch(workflow,/\n  push:/);
assert.match(workflow,/permissions:\s*\n  contents: read\s*\n/);
assert.doesNotMatch(build,/attestations:\s*write|id-token:\s*write|artifact-metadata:\s*write/,
 'PR build must remain read-only');
assert.match(build,/timeout-minutes:\s*30/);
assert.match(build,/anchore\/sbom-action@e22c389904149dbc22b58101806040fa8d37a610/);
assert.match(build,/output-file:\s*build\/guardian\.spdx\.json/);
assert.match(build,/upload-artifact:\s*false/);
assert.match(build,/upload-release-assets:\s*false/);
assert.match(build,/src-tauri\/target\/release\/bundle\/nsis\/\*-setup\.exe/);
assert.match(build,/name:\s*rumbo-guardian-windows-trust-candidate/);
assert.match(build,/build\/guardian\.spdx\.json/);
assert.match(build,/actions\/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02/);
assert.match(attest,/if:\s*github\.event_name == 'workflow_dispatch'/);
assert.match(attest,/needs:\s*windows-nsis/);
assert.match(attest,/timeout-minutes:\s*10/);
assert.match(attest,/permissions:\s*\n\s+contents: read\s*\n\s+id-token: write\s*\n\s+attestations: write\s*\n\s+artifact-metadata: write/);
assert.match(attest,/actions\/download-artifact@d3f86a106a0bac45b974a628896c90dbdf5c8093/);
assert.match(attest,/actions\/attest@1e69f48acb82d1966a394da916b4c1698aa569d6/g);
assert.equal((attest.match(/uses:\s*actions\/attest@/g)||[]).length,2);
assert.match(attest,/sbom-path:\s*'attest-candidate\/build\/guardian\.spdx\.json'/);
assert.match(attest,/subject-path:\s*'attest-candidate\/src-tauri\/target\/release\/bundle\/nsis\/\*-setup\.exe'/);
assert.doesNotMatch(workflow,/TAURI_SIGNING_PRIVATE_KEY|softprops\/action-gh-release|gh release create|push-to-registry:\s*true|deploy:/);
console.log('GUARDIAN_DESKTOP_TRUST_ISOLATED_PERMISSIONS_PASS');

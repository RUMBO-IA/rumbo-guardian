'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const file = path.join(root, '.github/workflows/desktop-install-lab.yml');
assert.ok(fs.existsSync(file));
const source = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
assert.match(source, /^on:\n  workflow_dispatch:\n/m);
assert.doesNotMatch(source, /^\s{2}(push|pull_request|pull_request_target|schedule):/m);
assert.match(source, /^permissions:\n  contents: read$/m);
assert.match(source, /timeout-minutes:\s*35/);
assert.match(source, /actions\/checkout@[a-f0-9]{40}/);
assert.match(source, /persist-credentials:\s*false/);
assert.match(source, /actions\/setup-node@[a-f0-9]{40}/);
assert.match(source, /node-version:\s*'22'/);
assert.match(source, /dtolnay\/rust-toolchain@[a-f0-9]{40}/);
assert.match(source, /toolchain:\s*'1\.98\.1'/);
assert.match(source, /npm run release:validate/);
assert.match(source, /node tests\/desktop-install-lab\.test\.js/);
assert.match(source, /npm run check/);
assert.match(source, /npm test/);
assert.match(source, /cargo check --locked/);
assert.match(source, /@tauri-apps\/cli@2\.11\.4 build --bundles nsis -- --locked/);
assert.match(source, /LOCALAPPDATA/);
assert.match(source, /Start-Process -FilePath \$installer.FullName/);
assert.match(source, /Start-Process -FilePath \$appExe/);
assert.match(source, /Stop-Process -Id \$appProcess.Id/);
assert.match(source, /uninstall\*\.exe/);
assert.match(source, /residual_files/);
assert.match(source, /if: always\(\)/);
assert.match(source, /actions\/upload-artifact@[a-f0-9]{40}/);
assert.doesNotMatch(source, /id-token:\s*write|attestations:\s*write|artifact-metadata:\s*write|contents:\s*write/);
assert.doesNotMatch(source, /TAURI_SIGNING_PRIVATE_KEY|gh release create|softprops\/action-gh-release|deploy:|git push/);
console.log('GUARDIAN_DESKTOP_INSTALL_LAB_MANUAL_POLICY_PASS');
